#!/usr/bin/env python3
"""Generate a synthetic half-hourly grid for dry-running the M1 pilot.

ILLUSTRATIVE ONLY. This is not Jamali data and must never be reported as a
Jamali MEF estimate.

Toy merit order (deliberately simple so the regression is recoverable):
- Must-run geothermal + other
- Coal fills residual up to a fixed baseload ceiling
- Gas (then oil) takes everything above that ceiling

So coal is marginal at night/low load (true MEF ≈ 1.00) and gas is
marginal at the evening peak (true MEF ≈ 0.42). The overall OLS β should
land between those values.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parent / "toy_data"
SEED = 7

FACTORS = {
    "coal": 1.00,
    "gas": 0.42,
    "oil": 0.75,
    "geo": 0.00,
    "other": 0.05,
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)

    index = pd.date_range("2024-01-01", periods=48 * 366, freq="30min", inclusive="left")
    hour = index.hour + index.minute / 60.0
    doy = index.dayofyear.astype(float)

    # Night demand sits below the coal ceiling; evening peak pushes onto gas.
    base = 15_500.0
    seasonal = 800.0 * np.sin(2 * np.pi * (doy - 45) / 365.25)
    daily = 1_500.0 * (0.45 + 0.55 * np.sin(2 * np.pi * (hour - 7) / 24.0))
    evening = 3_200.0 * np.exp(-0.5 * ((hour - 19.0) / 1.8) ** 2)
    noise = rng.normal(0.0, 80.0, size=len(index))
    demand_mw = np.clip(base + seasonal + daily + evening + noise, 12_500.0, None)

    geo_mw = np.full(len(index), 700.0)
    other_mw = np.full(len(index), 800.0)

    # Coal baseload ceiling: below this residual, coal is marginal.
    coal_ceiling = 14_500.0
    residual = np.maximum(demand_mw - geo_mw - other_mw, 0.0)
    coal_mw = np.minimum(residual, coal_ceiling)
    after_coal = residual - coal_mw

    gas_cap = 6_000.0
    gas_mw = np.minimum(after_coal, gas_cap)
    oil_mw = after_coal - gas_mw

    demand_mwh = demand_mw * 0.5
    gen_coal_mwh = coal_mw * 0.5
    gen_gas_mwh = gas_mw * 0.5
    gen_oil_mwh = oil_mw * 0.5
    gen_geo_mwh = geo_mw * 0.5
    gen_other_mwh = other_mw * 0.5

    co2 = (
        gen_coal_mwh * FACTORS["coal"]
        + gen_gas_mwh * FACTORS["gas"]
        + gen_oil_mwh * FACTORS["oil"]
        + gen_geo_mwh * FACTORS["geo"]
        + gen_other_mwh * FACTORS["other"]
    ) + rng.normal(0.0, 6.0, size=len(index))

    true_marginal = np.where(
        oil_mw > 1.0,
        "oil",
        np.where(gas_mw > 1.0, "gas", "coal"),
    )

    interval = pd.DataFrame(
        {
            "timestamp": index,
            "demand_mwh": demand_mwh,
            "gen_coal_mwh": gen_coal_mwh,
            "gen_gas_mwh": gen_gas_mwh,
            "gen_oil_mwh": gen_oil_mwh,
            "gen_geo_mwh": gen_geo_mwh,
            "gen_other_mwh": gen_other_mwh,
            "interchange_mwh": rng.normal(10.0, 8.0, size=len(index)) * 0.5,
            "co2_tonnes": co2,
            "true_marginal_fuel": true_marginal,
        }
    )
    interval_path = OUT / "toy_interval_operations.csv"
    interval.to_csv(interval_path, index=False)

    factors_path = OUT / "toy_emission_factors.csv"
    pd.DataFrame(
        {"fuel": list(FACTORS.keys()), "tco2_per_mwh": list(FACTORS.values())}
    ).to_csv(factors_path, index=False)

    d = interval["demand_mwh"].diff()
    e = interval["co2_tonnes"].diff()
    corr = float(d.corr(e))
    share = interval["true_marginal_fuel"].value_counts(normalize=True).to_dict()

    meta = OUT / "TOY_DATA_README.txt"
    meta.write_text(
        "ILLUSTRATIVE SYNTHETIC DATA — NOT JAMALI\n"
        "Generated by generate_toy_data.py for dry-running pilot_m1/run_pilot.py.\n"
        "Do not cite these series as Indonesian operating evidence or as a Jamali MEF.\n"
        f"Sanity: corr(delta_demand, delta_co2) ≈ {corr:.3f}\n"
        f"Share of intervals by true marginal fuel: {share}\n"
        "Known marginal intensities: coal=1.00, gas=0.42, oil=0.75 tCO2/MWh.\n",
        encoding="utf-8",
    )

    print(f"Wrote {interval_path} ({len(interval)} rows)")
    print(f"Wrote {factors_path}")
    print(f"corr(delta_demand, delta_co2) = {corr:.3f}")
    print(f"marginal fuel shares = {share}")
    print(f"Wrote {meta}")


if __name__ == "__main__":
    main()
